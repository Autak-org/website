def build_images() -> None:
    os.makedirs(IMAGE_OUT, exist_ok=True)

    for source, (stem, width) in IMAGES.items():
        path = os.path.join(MEDIA_IN, source)
        if not os.path.exists(path):
            print(f"  missing photo {source}")
            continue

        image = Image.open(path).convert("RGB")
        if image.width > width:
            height = round(image.height * width / image.width)
            image = image.resize((width, height), Image.LANCZOS)

        out = os.path.join(IMAGE_OUT, f"{stem}.jpg")
        image.save(out, "JPEG", quality=82, optimize=True, progressive=True)
        print(f"  {stem}.jpg {image.width}x{image.height} {os.path.getsize(out) // 1024}KB")

    media_out = os.path.join(IMAGE_OUT, "media")
    os.makedirs(media_out, exist_ok=True)

    for source, (stem, width) in MEDIA.items():
        path = source_path(source)
        if not path:
            print(f"  missing media {source}")
            continue

        image = Image.open(path).convert("RGB")
        if image.width > width:
            height = round(image.height * width / image.width)
            image = image.resize((width, height), Image.LANCZOS)

        out = os.path.join(media_out, f"{stem}.jpg")
        image.save(out, "JPEG", quality=80, optimize=True, progressive=True)
        print(f"  media/{stem}.jpg {image.width}x{image.height} {os.path.getsize(out) // 1024}KB")

    portrait_out = os.path.join(IMAGE_OUT, "people")
    os.makedirs(portrait_out, exist_ok=True)

    for source, stem in PORTRAITS.items():
        path = os.path.join(MEDIA_IN, source)
        if not os.path.exists(path):
            print(f"  missing portrait {source}")
            continue

        image = Image.open(path)
        # Cutouts are transparent PNGs; flatten onto the card background so the
        # portraits share one look with the photographic ones.
        if image.mode in ("RGBA", "LA", "P"):
            image = image.convert("RGBA")
            canvas = Image.new("RGBA", image.size, (240, 240, 240, 255))
            canvas.alpha_composite(image)
            image = canvas.convert("RGB")
        else:
            image = image.convert("RGB")

        side = min(image.width, image.height)
        left = (image.width - side) // 2
        image = image.crop((left, 0, left + side, side))
        image = image.resize((PORTRAIT_SIZE, PORTRAIT_SIZE), Image.LANCZOS)

        out = os.path.join(portrait_out, f"{stem}.jpg")
        image.save(out, "JPEG", quality=82, optimize=True, progressive=True)

    print(f"  portraits: {len(PORTRAITS)} -> {portrait_out}")

    build_videos(media_out)


def build_videos(poster_dir: str) -> None:
    """Copies the clips to /videos and grabs a poster frame with ffmpeg."""
    import subprocess

    video_out = os.path.join(ROOT, "public", "videos")
    os.makedirs(video_out, exist_ok=True)

    for source, (stem, timestamp) in VIDEOS.items():
        path = os.path.join(MEDIA_IN, source)
        if not os.path.exists(path):
            print(f"  missing video {source}")
            continue

        shutil.copyfile(path, os.path.join(video_out, f"{stem}.mp4"))

        poster = os.path.join(poster_dir, f"video-{stem}.jpg")
        result = subprocess.run(
            [
                "ffmpeg", "-y", "-loglevel", "error",
                "-ss", timestamp, "-i", path,
                "-frames:v", "1", "-vf", "scale=1200:-2", "-q:v", "4",
                poster,
            ],
            capture_output=True,
        )
        if result.returncode != 0:
            print(f"  poster failed for {stem}: {result.stderr.decode()[:120]}")
            continue

        print(f"  videos/{stem}.mp4 + poster")

    for source, (stem, width) in LOGOS.items():
        path = os.path.join(MEDIA_IN, source)
        if not os.path.exists(path):
            print(f"  missing logo {source}")
            continue

        image = Image.open(path).convert("RGBA")
        if image.width > width:
            height = round(image.height * width / image.width)
            image = image.resize((width, height), Image.LANCZOS)

        out = os.path.join(IMAGE_OUT, f"{stem}.png")
        image.save(out, "PNG", optimize=True)
        print(f"  {stem}.png {image.width}x{image.height} {os.path.getsize(out) // 1024}KB")


