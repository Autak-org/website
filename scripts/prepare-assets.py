def source_path(name: str) -> str | None:
    for folder in (MEDIA_IN, SHOP_IN):
        candidate = os.path.join(folder, name)
        if os.path.exists(candidate):
            return candidate
    return None

# Only latin coverage is needed for a German/English site; dropping devanagari,
# cyrillic, greek and vietnamese removes roughly two thirds of the font payload.
KEEP_SUBSETS = {"latin", "latin-ext"}
KEEP_WEIGHTS = {
    "Poppins": {"400", "500", "600", "700", "800"},
    "Comfortaa": {"400", "700"},
}

FACE_RE = re.compile(
    r"/\*\s*(?P<subset>[\w-]+)\s*\*/\s*@font-face\s*\{(?P<body>[^}]+)\}",
    re.MULTILINE,
)


def parse_faces(css: str):
    for match in FACE_RE.finditer(css):
        body = match.group("body")

        def field(name: str) -> str:
            found = re.search(rf"{name}:\s*([^;]+);", body)
            return found.group(1).strip() if found else ""

        url = re.search(r"url\(([^)]+)\)", body)
        if not url:
            continue

        yield {
            "subset": match.group("subset"),
            "family": field("font-family").strip("'\""),
            "style": field("font-style"),
            "weight": field("font-weight"),
            "range": field("unicode-range"),
            "url": url.group(1),
        }


def cached_woff2_for(url: str) -> str | None:
    """The proxy stored each file as md5(base64(originalUrl)).cache.woff2."""
    import base64
    import hashlib

    remote = re.sub(r"^.*\?url=", "", url)
    from urllib.parse import unquote

    remote = unquote(remote)
    digest = hashlib.md5(base64.b64encode(remote.encode())).hexdigest()
    path = os.path.join(FONT_CACHE, f"{digest}.cache.woff2")
    return path if os.path.exists(path) else None


def build_fonts() -> None:
    os.makedirs(FONT_OUT, exist_ok=True)
    seen: set[tuple[str, str, str, str]] = set()
    rules: list[str] = []

    for name in sorted(os.listdir(FONT_CACHE)):
        if not name.endswith(".cache.css"):
            continue

        with open(os.path.join(FONT_CACHE, name), encoding="utf-8") as handle:
            css = handle.read()

        for face in parse_faces(css):
            family = face["family"]
            if family not in KEEP_WEIGHTS:
                continue
            if face["subset"] not in KEEP_SUBSETS:
                continue
            if face["weight"] not in KEEP_WEIGHTS[family]:
                continue
            if face["style"] != "normal":
                continue

            key = (family, face["weight"], face["style"], face["subset"])
            if key in seen:
                continue

            source = cached_woff2_for(face["url"])
            if not source:
                continue

            seen.add(key)
            filename = f"{family.lower()}-{face['weight']}-{face['subset']}.woff2"
            shutil.copyfile(source, os.path.join(FONT_OUT, filename))

            rules.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                f"  font-style: {face['style']};\n"
                f"  font-weight: {face['weight']};\n"
                "  font-display: swap;\n"
                f"  src: url('/fonts/{filename}') format('woff2');\n"
                f"  unicode-range: {face['range']};\n"
                "}"
            )

    style_dir = os.path.join(ROOT, "src", "styles")
    os.makedirs(style_dir, exist_ok=True)
    out = os.path.join(style_dir, "fonts.css")
    header = "/* Generated by scripts/prepare-assets.py - do not edit by hand. */\n"
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(header + "\n".join(rules) + "\n")

    print(f"fonts: {len(seen)} faces -> {out}")


